const packs: Record<Lang, typeof fr> = { fr, en, ar };

export function learnText(lang: Lang, key: keyof typeof fr, vars?: Record<string, string | number>): string {
  const raw = packs[lang][key] ?? fr[key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] === undefined ? '' : String(vars[name])));
}
